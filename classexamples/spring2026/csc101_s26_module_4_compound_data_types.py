"""## Dictionaries"""

person = {
    "name": "Alice",
    "age" : 30,
    "city": "New York"
}

print(f"{person=}")
print(person.keys())
print(person.values())
print(person.items())


print("Accessing & modifying in a dictionary")
print(f"{person['name']=}")
print(f"{person['city']=}")
print(f"{person['age']=}")

person['age'] = 31
print(f"{person=}")
person["name"]='Bob'
person['city']="Phoenix"
print(f"{person=}")

print("Use a loop to go through a dictionary")
# iteratinng through a dictionary
for key in person:
  print(f"{key=} {person[key]=}")

for key, value in person.items():
    print(f"{key=} {value=}")