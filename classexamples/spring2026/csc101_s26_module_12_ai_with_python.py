import matplotlib.pyplot as plt
import pandas as pd

import torch
import torch.nn as nn
import torch.nn.functional as F

from sklearn.model_selection import train_test_split

"""## Download & prep the Iris Data set

Fisher, R. A.. (1988). Iris. UCI Machine Learning Repository. https://doi.org/10.24432/C56C76.

Linked from https://gist.github.com/curran/
"""

url = 'https://gist.githubusercontent.com/curran/a08a1080b88344b0c8a7/raw/0e7a9b0a5d22642a06d3d5b9bcbad9890c8ee534/iris.csv'
df = pd.read_csv(url)
df.head()
df.tail()

# convert the species column to a number
df['species'] = pd.Categorical(df['species']).codes
df

"""## Prepare the training data"""

from re import X
# Split the features and lables
X = df.drop('species', axis=1)
y = df['species']

# Split the data into training and testing sets
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.2, random_state=50)

# Convert to tensors
X_train = torch.FloatTensor(X_train.values)
X_test = torch.FloatTensor(X_test.values)
y_train = torch.LongTensor(y_train.values)
y_test = torch.LongTensor(y_test.values)

"""## Create the model"""

# Create a model class based on nn.Module
class IrisModel(nn.Module):
  # input layer (in_features)
  # 2 hidden layers (layer h1: 8 nodes, layer h2: 12 nodes)
  # output layer (out_features)

  def __init__(self, in_features=4, h1=8, h2=12, out_features=3):
    super().__init__()
    self.fc1 = nn.Linear(in_features, h1)   # input layer -> hidden layer 1
    self.fc2 = nn.Linear(h1, h2)            # hidden layer 1 -> hidden layer 2
    self.out = nn.Linear(h2, out_features)  # hidden layer 2 -> output layer

  def forward(self, x):
    x = F.relu(self.fc1(x))
    x = F.relu(self.fc2(x))
    x = self.out(x)
    return x

"""# Instantiate & prepare the module"""

torch.manual_seed(50)

model = IrisModel()

# Set the measurement criterion, optimizer, and learning rate
criterion = nn.CrossEntropyLoss()
optimizer = torch.optim.Adam(model.parameters(), lr=0.01)

"""## Train the model"""

epochs = 200
losses = []

for i in range(epochs):
  y_pred = model.forward(X_train)
  loss = criterion(y_pred, y_train)
  losses.append(loss)

  if i % 10 == 0:
    print(f'Epoch: {i} Loss: {loss}')

  optimizer.zero_grad()
  loss.backward()
  optimizer.step()

"""## Graph our results"""

plt.plot(range(epochs), [loss.detach().numpy() for loss in losses])
plt.ylabel('Loss')
plt.xlabel('Epoch')

"""## Evalulate the model"""

with torch.no_grad():
  y_eval = model.forward(X_test)
  loss = criterion(y_eval, y_test)

print(f"Loss: {loss}")

"""## Classify a new data point"""

new_iris = torch.tensor([5.9, 3.0, 5.1, 1.8])
with torch.no_grad():
  print(model.forward(new_iris))

"""## Save the model for later use"""

torch.save(model.state_dict(), 'iris_model.pt')

"""## Work with a saved model"""

new_model = IrisModel()
new_model.load_state_dict(torch.load('iris_model.pt'))
new_model.eval()

another_iris = torch.tensor([4.9, 3.1, 6.1, 1.3])

with torch.no_grad():
    print(new_model.forward(new_iris))
    print(new_model.forward(another_iris))

def predict_species(features):
  # Convert the list of features to a PyTorch tensor
  input_tensor = torch.tensor(features)

  # Make a prediction with the loaded model
  with torch.no_grad():
    output = new_model.forward(input_tensor)

  # Apply softmax to get probabilities and determine the predicted class
  probabilities = F.softmax(output, dim=0)
  predicted_class = torch.argmax(probabilities).item()

  # Map the class index back to species name
  species_map = {0: 'setosa', 1: 'versicolor', 2: 'virginica'}
  predicted_species = species_map[predicted_class]

  print(f"Input features: {features}")
  print(f"Predicted species: {predicted_species} (Class: {predicted_class})")
  print(f"Probabilities: {probabilities}")

  return predicted_species

"""Let's test our `predict_species` function with a new data point."""

