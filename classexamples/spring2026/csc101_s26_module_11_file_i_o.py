"""## Reading a file line by line"""

# Write a file with multiple lines
characters = [
    "Katniss Everdeen",
    "Peeta Mellark",
    "Gale Hawthorne",
    "Haymitch Abernathy",
    "Effie Trinket",
    "Primrose Everdeen",
    "Coriolanus Snow",
    "Finnick Odair"
]

with open('hungergames.txt', 'w') as my_file:
  for name in characters:
    my_file.write(name + '\n')

# Read all lines into a list
my_file = open("hungergames.txt")
contents = my_file.read()
print(f"{contents}")
my_file.close()

# Read file line by line
with open('hungergames.txt') as my_file:
  lineno = 1
  for line in my_file:
    print(f"{lineno}: {line.strip()}")
    lineno += 1

# Read in a file by chunks
with open('hungergames.txt') as my_file:
  chunk_number = 1;
  while line := my_file.read(15):
    print(f"{chunk_number}: {line.strip()}")
    chunk_number += 1