"""### For Loops & Collections
You can also loop through a string, list, or other compound data structure using "in".
"""

print("Loop through characters of a string")
for ch in "CGCC":
  print(f"{ch=}")

print()
print("Loop through characters of a string, build a new string")
new_str = ""
for ch in "CGCC":
  new_str += ch + '-'
print(new_str)

vals = [3, 8, 5, 6, 9]
print()
print("Loop through a list")
for val in vals:
  print(f"{val=}")

print()
print("Loop through a list, sum element")
total = 0
for val in vals:
  total += val
print(f"{total=}")

"""### Looping through dictionaries"""

couples = {
    "Elizabeth Bennet": "Mr. Darcy",
    "Jane Bennet": "Mr. Bingley",
    "Emma Woodhouse": "Mr. Knightley",
    "Anne Elliot": "Captain Wentworth"
}

print()
print("Loop through a dictionary")
for name in couples:
  print(f"{name}")

print()
print("Loop through dictionary and get values")
for name in couples:
  print(f"{name} is with {couples[name]}")

print()
print("Loop through dictionary and get keys and values")
for name, partner in couples.items():
  print(f"{name} is with {partner}")

