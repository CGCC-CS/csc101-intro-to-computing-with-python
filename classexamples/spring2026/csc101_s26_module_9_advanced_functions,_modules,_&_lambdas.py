"""## Advanced parameters & arguments"""

def greet(name, greeting='Hello'):
  """ Create a message with an optional greeting """
  print(f"{greeting}, {name}!")

greet("world")
greet("Alice")
greet("Bob", "HELLO")
greet("Doc", "What's up")

print()

def greet_class(*args):
  print(f"Need to greet: {args}")
  for name in args:
    print(f"Hello, {name}")

greet_class("Bob", "Alice")
greet_class("Theodore", "Franklin", "Anne", "Thomas", "Janice")

print()

def example(**kwargs):
  print(f"Arguments: {kwargs}")
  for key, value in kwargs.items():
    print(f"{key} = {value}")

example(name="John", age="22", city="Gilbert", major="Math")

"""## Lambdas"""

square = lambda x: x**2

for value in [5, -4, pi, 16, 9, -1, 77, 96]:
  print(f"The square of {value} is {square(value)}")

is_even = lambda n: n % 2 == 0

for value in [5, -4, pi, 16, 9, -1, 77, 96]:
  if is_even(value):
    print(f"{value} is even ")