"""### Summing up numbers

A common loop pattern is to keep a running total.  In this example, we use the variable *sum* to keep track of the total of each number entered.  Note that we initialize sum to 0 before the loop!

ALso notice that we use -1 as the sentinel to indicate the user is done entering numbers and is ready to see the sum.  
"""

print("Sum numbers until -1 is entered")
num = int(input("Enter a number: "))
total = 0
while num != -1:
  total += num
  num = int(input("Enter a number: "))
print("The sum is", total)

"""## For Loops"""

