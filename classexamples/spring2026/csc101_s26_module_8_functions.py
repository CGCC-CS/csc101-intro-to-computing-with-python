"""### Function to make a diamond"""

def diamond_outline(size):
  mid = size // 2
  for row in range(size):
    for col in range(size):
      if abs(row - mid) + abs(col - mid) == mid:
        print("*", end="")
      else:
        print(" ", end="")
    print()

diamond_outline(3)
diamond_outline(7)
diamond_outline(11)

for size in range(1,11,2):
  diamond_outline(size)

